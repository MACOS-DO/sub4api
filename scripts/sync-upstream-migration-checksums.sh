#!/usr/bin/env bash
# 从上游 Sub2API 重新生成 backend/migrations/upstream_checksums.txt。
# 合并上游后运行一次；backend/migrations/upstream_checksums_test.go 会校验
# 同名迁移文件与上游完全一致（checksum 算法与 migrations_runner 相同：去首尾空白后 sha256）。
#
# 默认以 HEAD 与 sub2api/main 的 merge-base（即最近一次合入的上游提交）为基准，
# 避免把尚未合入的上游新迁移写进清单。
#
# 用法：scripts/sync-upstream-migration-checksums.sh [upstream-ref]
set -euo pipefail
root=$(git rev-parse --show-toplevel)
out="$root/backend/migrations/upstream_checksums.txt"
if [[ $# -ge 1 ]]; then
  ref=$1
else
  git fetch --quiet sub2api
  ref=$(git merge-base HEAD sub2api/main)
fi
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
git ls-tree --name-only "$ref" -- backend/migrations/ | grep '\.sql$' | sort | while read -r path; do
  sum=$(git show "$ref:$path" | python3 -c 'import hashlib,sys; print(hashlib.sha256(sys.stdin.buffer.read().decode().strip().encode()).hexdigest())')
  printf '%s  %s\n' "$sum" "${path##*/}"
done >"$tmp"
{
  printf '# Generated by scripts/sync-upstream-migration-checksums.sh from upstream %s.\n' "$(git rev-parse --short "$ref")"
  printf '# Upstream migrations must not be modified; add a new Sub4API migration instead.\n'
  cat "$tmp"
} >"$out"
echo "wrote $(wc -l <"$tmp") entries to ${out#$root/}"
